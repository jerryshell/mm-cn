_COMPILED = [(_re.compile(pat) if rx else None, pat, rep, rx)
             for pat, rep, rx in FIXES]


def apply_fixes(text):
    for cre, pat, rep, rx in _COMPILED:
        if rx:
            text = cre.sub(rep, text)
        elif pat in text:
            text = text.replace(pat, rep)
    return text


